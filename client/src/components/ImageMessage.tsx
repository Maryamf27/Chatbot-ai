import { useState } from "react";
import type { ModelId } from "../types";

type Props = {
  imageUrl: string;
  prompt?: string;
  model?: ModelId;
};

export function ImageMessage({ imageUrl, prompt, model }: Props) {
  const [errored, setErrored] = useState(false);

  if (!imageUrl) return null;

  return (
    <div className="image-message">
      {errored ? (
        <div className="image-message-error" role="alert">
          <span>🖼️</span>
          <p>Image could not be loaded.</p>
          {prompt ? <p className="image-message-prompt">Prompt: {prompt}</p> : null}
        </div>
      ) : (
        <>
          <img
            src={imageUrl}
            alt={prompt ?? model ? `Generated by ${model ?? "model"}` : "Generated image"}
            className="image-message-img"
            onError={() => setErrored(true)}
            loading="lazy"
          />
          {prompt ? (
            <p className="image-message-prompt">
              <strong>Prompt:</strong> {prompt}
            </p>
          ) : null}
        </>
      )}
    </div>
  );
}
